// Regenerates src/ui/icon-registry.js with only the Lucide icons referenced in src/.
// Usage: npm run icons
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const lucide = await import(pathToFileURL(path.join(root, 'node_modules/lucide/dist/esm/lucide.mjs')).href);

const files = [];
const walk = (dir) => {
  for (const f of fs.readdirSync(dir)) {
    const p = path.join(dir, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (p.endsWith('.js') && !p.endsWith('icon-registry.js')) files.push(p);
  }
};
walk(path.join(root, 'src'));

const pascal = (n) => n.split('-').map((s) => s[0].toUpperCase() + s.slice(1)).join('');
const names = new Set();
for (const f of files) {
  const src = fs.readFileSync(f, 'utf8');
  for (const m of src.matchAll(/icon\(\s*([^,)]+)/g)) for (const s of m[1].matchAll(/'([a-z0-9-]+)'/g)) names.add(s[1]);
  for (const m of src.matchAll(/icon:\s*'([a-z0-9-]+)'/g)) names.add(m[1]);
  // segmented options: ['value', 'icon-name', '中文提示']
  for (const m of src.matchAll(/\[\s*'[a-z-]+'\s*,\s*'([a-z0-9-]+)'\s*,\s*'[^']*[^\x00-\x7f][^']*'\s*\]/g)) names.add(m[1]);
}

const ok = [], missing = [];
for (const n of [...names].sort()) (lucide[pascal(n)] ? ok : missing).push(n);
fs.writeFileSync(
  path.join(root, 'src/ui/icon-registry.js'),
  `// Generated by scripts/gen-icons.mjs — the Lucide icons used by the app.\nexport {\n${ok.map((n) => `  ${pascal(n)},`).join('\n')}\n} from 'lucide';\n`,
);
console.log(`icons: ${ok.length}`);
if (missing.length) console.log(`missing: ${missing.join(', ')}`);
